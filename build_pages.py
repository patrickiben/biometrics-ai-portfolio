def hexc(c):
    return '#%02x%02x%02x' % tuple(c[:3])


def mix(a, b, p):
    return tuple(round(a[i] * p + b[i] * (1 - p)) for i in range(3)) + (1.0,)


def rgb_triplet(v, bg=None):
    c = rgba(v)
    if c[3] < 1 and bg is not None:
        c = over(c, rgba(bg))
    return f'{c[0]},{c[1]},{c[2]}'


# Named series colors for the apps, each from site tokens: fg (text), bg (chip), line (chip border),
# fill (a plot mark or a bar) and tile (a heatmap cell behind --ink text). bg is the soft token over
# --surface; line is its own token where the site has one, else 45% fill over bg; tile is TILE_MIX of
# fill over --surface. Which app level uses which tone stays in each app (RED -> red, watch -> blue).
TONE_SPEC = OrderedDict([
    # name: (fg, soft or bg, fill, line or None)
    ('red', ('red', 'red-soft', 'red', None)),
    ('amber', ('amber', 'amber-soft', 'amber', None)),
    ('green', ('green', 'green-soft', 'green', None)),
    ('blue', ('blue', 'blue-soft', 'blue', None)),
    ('violet', ('tools-fg', 'tools-bg', 'violet', 'tools-line')),
    ('orange', ('gap-fg', 'gap-bg', 'note-line', 'gap-line')),
    ('accent', ('accent-ink', 'accent-soft', 'accent', None)),
    ('neutral', ('muted', 'surface-2', 'faint', 'line-2')),
])
TILE_MIX = {'dark': 0.36, 'light': 0.36}


def tones_of(T, mode):
    t = {k[2:]: v for k, v in T.items()}
    s = rgba(t['surface'])
    out = OrderedDict()
    for k, (fg, soft, fill, line) in TONE_SPEC.items():
        f, b, fl = rgba(t[fg]), over(rgba(t[soft]), s), rgba(t[fill])
        ln = rgba(t[line]) if line else mix(fl, b, .45)
        out[k] = OrderedDict([('fg', hexc(f)), ('bg', hexc(b)), ('line', hexc(ln)), ('fill', hexc(fl)),
                              ('tile', hexc(mix(fl, s, TILE_MIX[mode])))])
    return out


TONES = OrderedDict([('dark', tones_of(DARK, 'dark')), ('light', tones_of(LIGHT, 'light'))])
for mode, T in (('dark', DARK), ('light', LIGHT)):
    c = {k[2:]: v for k, v in T.items()}
    surf = [('bg', c['bg']), ('surface', c['surface']), ('surface-2', c['surface-2']), ('surface-3', c['surface-3'])]
    for k, v in TONES[mode].items():
        checks = [(f'tone {k} fg on its bg', v['fg'], v['bg'], 4.5), (f'ink on tone {k} tile', c['ink'], v['tile'], 4.5)]
        checks += [(f'tone {k} fg on {n}', v['fg'], s, 4.5) for n, s in surf]
        checks += [(f'tone {k} fill on {n}', v['fill'], s, 3.0) for n, s in surf]
        for name, a, b, floor in checks:
            r = ratio(rgba(a), rgba(b))
            if r < floor - 1e-9:
                fail(f'contrast ({mode}, apps): {name} is {r:.2f}:1, below {floor}:1')

