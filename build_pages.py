def card(m, cls='card', thumb=True, eager=False, priority=False, large=False, run_local=False, item=False, heading='h3', max_links=None):
    href = m['href']
    title_link = f'<a href="{esc(href)}">{esc(m["title"])}</a>'
    th = thumb_link(m, href, eager, priority, large) if thumb else ''
    parts = []
    if m.get('eyebrow'):
        parts.append(f'<p class="eyebrow" title="{esc(m["eyebrow"])}">{esc(m["eyebrow"])}</p>')
    parts.append(f'<{heading}>{title_link}</{heading}>')
    parts.append(chips(m))
    parts.append(f'<p class="sum">{esc(m["summary"])}</p>')
    labels = m.get('labels', [])
    if len(labels) >= 2 and any(':' in l['text'] for l in labels):
        parts.append(labs_dl(labels))
    if m.get('shots'):
        figs = []
        for s in m['shots']:
            i = img(s['thumb']) or f'<img src="{s["img"]}" width="1440" height="960" alt="{esc(s["alt"])}" loading="lazy" decoding="async">'
            figs.append(f'<figure><a class="thumb" href="{esc(s["href"])}" tabindex="-1">{i}</a>'
                        f'<figcaption><a href="{esc(s["href"])}">{esc(s["caption"])}</a></figcaption></figure>')
        parts.append('<div class="shots">' + ''.join(figs) + '</div>')
    f = fact_of(m)
    if f:
        parts.append(f'<p class="fact">{esc(f)}</p>')
    if run_local and m.get('run_local'):
        parts.append(f'<pre class="cmd" aria-label="Run in local R"><code>{esc(m["run_local"])}</code></pre>')
    parts.append(go((browser_links(m) + m['links'])[:max_links]))
    attrs = ''
    if item:
        attrs = f' data-item data-stages="{" ".join(m.get("stages", []))}" data-labels="{" ".join(sorted(set(mod_kinds(m))))}"'
    body = ''.join(p for p in parts if p)
    if 'card--feature' in cls:
        return f'<article class="{cls}"{seg_style(mod_kinds(m))}{attrs}>{th}<div class="body">{body}</div></article>'
    return f'<article class="{cls}"{seg_style(mod_kinds(m))}{attrs}>{th}{body}</article>'


