CSS_REGION = r'(/\* {name}:begin[^*]*\*/\n)(.*?)(/\* {name}:end \*/)'
HTML_REGION = r'(<!-- gen:{name} -->)(.*?)(<!-- /gen:{name} -->)'


def get_region(text, name, kind='css'):
    pat = (CSS_REGION if kind == 'css' else HTML_REGION).format(name=re.escape(name))
    m = re.search(pat, text, re.S)
    if not m:
        raise KeyError(name)
    return m.group(2)


def set_region(text, name, body, kind='css', path='?'):
    pat = (CSS_REGION if kind == 'css' else HTML_REGION).format(name=re.escape(name))
    m = re.search(pat, text, re.S)
    if not m:
        fail(f'{path}: region "{name}" is missing')
        return text
    return text[:m.start(2)] + body + text[m.end(2):]


TOKENS_SRC = rd('assets/theme/tokens.css')


def decls(block):
    return OrderedDict((k, v.strip()) for k, v in re.findall(r'(--[\w-]+)\s*:\s*([^;]+);', block))


DARK = decls(get_region(TOKENS_SRC, 'dark'))
STATIC = decls(get_region(TOKENS_SRC, 'static'))
light_region = get_region(TOKENS_SRC, 'light')
LIGHT = decls(light_region)
light_body = re.search(r':root:not\(\[data-theme="dark"\]\) \{\n(.*?)\n  \}', light_region, re.S).group(1)
light_lines = [ln.strip() for ln in light_body.splitlines() if ln.strip()]
if set(DARK) != set(LIGHT):
    fail('tokens.css: the dark and light blocks define different tokens: ' + ', '.join(sorted(set(DARK) ^ set(LIGHT))))


def light_copy():
    a = ':root[data-theme="light"] {\n' + ''.join('  ' + ln + '\n' for ln in light_lines) + '}\n'
    b = '@media print {\n  :root, :root[data-theme] {\n' + ''.join('    ' + ln + '\n' for ln in light_lines) + '  }\n}\n'
    return a + b


tokens_css = set_region(TOKENS_SRC, 'light-copy', light_copy(), path='assets/theme/tokens.css')
put('assets/theme/tokens.css', tokens_css)
TOKENS_BODY = tokens_css[tokens_css.index('/* dark:begin */'):]

