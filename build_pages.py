    if 'head' in present:
        t = set_region(t, 'head', '\n' + (inline_head() if kind == 'inline' else head_block(depth)), 'html', path)
    if 'topbar' in present:
        t = set_region(t, 'topbar', '\n' + topbar(section, depth, cur), 'html', path)
    if 'ui' in present:
        t = set_region(t, 'ui', '\n' + inline_ui(), 'html', path)
    if 'footer' in present:
        t = set_region(t, 'footer', '\n' + site_footer(depth), 'html', path)
    if path == 'index.html':
        t = home_regions(t)
    if path == 'quality.html':
        t = quality_regions(t)
    if kind != '404' and 'head' not in present:
        fail(f'{path}: no gen:head region')
    if 'topbar' not in present and kind != '404':
        fail(f'{path}: no gen:topbar region')
    put(path, t)


