    a = ':root[data-theme="light"] {\n' + ''.join('  ' + ln + '\n' for ln in light_lines) + '}\n'
    b = '@media print {\n  :root, :root[data-theme] {\n' + ''.join('    ' + ln + '\n' for ln in light_lines) + '  }\n}\n'
    return a + b


