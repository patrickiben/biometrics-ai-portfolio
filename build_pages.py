"""
build_pages.py: generate the portfolio console's shared pieces, each from one source.

  python3 build_pages.py           write every generated file and region
  python3 build_pages.py --check   write nothing; exit 1 if any generated byte differs, a source
                                   is missing, a readout disagrees with its source file, a token
                                   pair fails its contrast floor (the apps' tones included), an app
                                   source writes a color literal, or a thumbnail breaks its budget

Sources and what is generated from them (Python 3 standard library only):
  assets/theme/tokens.css  ->  its own light-theme copies; the token region of site.css; the Quarto
                               token files _quarto-tokens-dark.scss and _quarto-tokens-light.scss;
                               assets/theme/theme.R and its copy in apps/_shared/portfolio_app.R
                               (the Shiny apps' tones, CSS variables and component rules); the
                               inline copies in self-contained pages
  site.css (chrome, shared) -> _quarto-site.scss and the inline copies
  assets/ui.js             ->  the inline copies (pages whose security policy allows no file loads)
  capabilities.json        ->  the home page regions, lifecycle.html, apps.html, methods.html and
                               the readouts on quality.html
  ledger.json, teeth summary.json, the study outputs -> the status strip and the glance panel
  _partials/               <-  the top bar, head and Quarto head partials that the R page generators
                               (study/R/common.R, cqtc_hysteresis/R/page.R) and the Quarto pages read,
                               and the footer that .github/pages/build_site.R puts on the apps' launch pages
  rendered Quarto pages    ->  the guard on Quarto's mermaid post-processing (see MERMAID_GUARD)
Hand text outside the <!-- gen:NAME --> ... <!-- /gen:NAME --> markers (and # gen:NAME:begin ...
# gen:NAME:end in R files) is never touched.
Synthetic data only.
"""
