def app_theme_block(T, mode):
    t = {k[2:]: v for k, v in T.items()}
    tn = TONES[mode]
    s = t['surface']
    v = OrderedDict()
    v['color-scheme'] = mode
    for k, val in T.items():
        v[k[2:]] = val
    for k, x in tn.items():
        for part, val in x.items():
            v[f'tone-{k}-{part}'] = val
    bs = OrderedDict([
        ('body-bg', t['bg']), ('body-bg-rgb', rgb_triplet(t['bg'])), ('body-color', t['text']), ('body-color-rgb', rgb_triplet(t['text'])),
        ('emphasis-color', t['ink']), ('emphasis-color-rgb', rgb_triplet(t['ink'])), ('heading-color', t['ink']),
        ('secondary-color', t['muted']), ('secondary-color-rgb', rgb_triplet(t['muted'])),
        ('secondary-bg', t['surface-2']), ('secondary-bg-rgb', rgb_triplet(t['surface-2'])),
        ('tertiary-color', t['faint']), ('tertiary-color-rgb', rgb_triplet(t['faint'])),
        ('tertiary-bg', t['surface-3']), ('tertiary-bg-rgb', rgb_triplet(t['surface-3'])),
        ('border-color', t['line-2']), ('border-color-translucent', t['line']),
        ('link-color', t['accent']), ('link-color-rgb', rgb_triplet(t['accent'])),
        ('link-hover-color', t['accent-ink']), ('link-hover-color-rgb', rgb_triplet(t['accent-ink'])), ('code-color', t['accent-ink']),
        ('focus-ring-color', t['accent-ring']), ('highlight-bg', tn['amber']['bg']), ('highlight-color', t['ink']),
        ('form-valid-color', t['green']), ('form-valid-border-color', t['green']),
        ('form-invalid-color', t['red']), ('form-invalid-border-color', t['red']),
    ])
    for name, tone, base in (('primary', 'accent', t['accent']), ('success', 'green', t['green']), ('info', 'blue', t['blue']),
                             ('warning', 'amber', t['amber']), ('danger', 'red', t['red']), ('secondary', 'neutral', t['muted'])):
        bs[name] = base
        bs[name + '-rgb'] = rgb_triplet(base)
        bs[name + '-text-emphasis'] = tn[tone]['fg']
        bs[name + '-bg-subtle'] = tn[tone]['bg']
        bs[name + '-border-subtle'] = tn[tone]['line']
    for k, val in bs.items():
        v['bs-' + k] = val
    v['bp-accent-rgb'] = rgb_triplet(t['accent'])
    v['bp-sel-rgb'] = rgb_triplet(tn['accent']['bg'])
    v['bp-sel-text-rgb'] = rgb_triplet(t['ink'])
    v['bp-sel-link-rgb'] = rgb_triplet(t['accent-ink'])
    v['bp-check'] = CHECK_SVG.format(c=t['on-accent'].replace('#', '%23'))
    v['bp-radio'] = RADIO_SVG.format(c=t['on-accent'].replace('#', '%23'))
    sel = 'html:not([data-bs-theme=light])' if mode == 'dark' else 'html[data-bs-theme=light]'
    return sel + '{' + ';'.join(f'{k}:{val}' if k == 'color-scheme' else f'--{k}:{val}' for k, val in v.items()) + '}'


