def r_vec(T):
    t = {k[2:]: v for k, v in T.items()}
    keys = ['bg', 'surface', 'surface-2', 'line', 'line-2', 'ink', 'text', 'muted', 'accent', 'accent-ink', 'blue', 'green', 'amber', 'red']
    return 'c(' + ', '.join(f'{k.replace("-", "_")} = "{t[k]}"' for k in keys) + ')'


