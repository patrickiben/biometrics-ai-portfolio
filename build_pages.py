        ('headings-color', t['ink']), ('text-muted', t['muted']),
        ('primary', t['accent']), ('secondary', t['muted']), ('success', t['green']), ('info', t['blue']),
        ('warning', t['amber']), ('danger', t['red']),
        ('link-color', t['accent']), ('link-hover-color', t['accent-ink']), ('border-color', t['line']),
        ('code-color', t['accent-ink']), ('code-block-bg', t['surface-3']), ('code-block-border-left', t['line-2']),
        ('card-bg', t['surface']), ('card-border-color', t['line-2']), ('card-cap-bg', t['surface-2']),
        ('table-border-color', t['line']), ('table-color', t['text']),
