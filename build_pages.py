# 2. contrast floors (WCAG 2.2 relative luminance)
# ---------------------------------------------------------------------------------------------
def rgba(v):
    v = v.strip()
    if v.startswith('#'):
        h = v[1:]
        if len(h) == 3:
            h = ''.join(c * 2 for c in h)
        return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (1.0,)
    m = re.match(r'rgba?\(([^)]+)\)', v)
    p = [x.strip() for x in m.group(1).split(',')]
    return (int(p[0]), int(p[1]), int(p[2]), float(p[3]) if len(p) > 3 else 1.0)


def over(fg, bg):
    a = fg[3]
    return tuple(round(fg[i] * a + bg[i] * (1 - a)) for i in range(3)) + (1.0,)


def lum(c):
    def ch(x):
        x = x / 255
        return x / 12.92 if x <= 0.04045 else ((x + 0.055) / 1.055) ** 2.4
    return 0.2126 * ch(c[0]) + 0.7152 * ch(c[1]) + 0.0722 * ch(c[2])


def ratio(a, b):
    la, lb = lum(a), lum(b)
    return (max(la, lb) + 0.05) / (min(la, lb) + 0.05)


LOWEST = {}
for theme, T in (('dark', DARK), ('light', LIGHT)):
    c = {k[2:]: v for k, v in T.items()}
    surf = [rgba(c[s]) for s in ('bg', 'surface', 'surface-2', 'surface-3')]
    pairs = []
    for t in ('ink', 'text', 'muted', 'faint', 'accent', 'accent-ink', 'blue', 'green', 'amber', 'red'):
        for s in surf:
            pairs.append((t, ratio(rgba(c[t]), s), 4.5))
    for t in ('blue', 'green', 'amber', 'red'):
        tint = over(rgba(c[t + '-soft']), rgba(c['surface']))
        pairs.append((t + ' on its tint', ratio(rgba(c[t]), tint), 4.5))
    pairs.append(('accent-ink on accent-soft', ratio(rgba(c['accent-ink']), over(rgba(c['accent-soft']), rgba(c['surface']))), 4.5))
    pairs.append(('on-accent on accent', ratio(rgba(c['on-accent']), rgba(c['accent'])), 4.5))
    for k in ('led', 'sup', 'tools', 'gap'):
        pairs.append((k + ' label', ratio(rgba(c[k + '-fg']), rgba(c[k + '-bg'])), 4.5))
    pairs.append(('text on note', ratio(rgba(c['text']), rgba(c['note-bg'])), 4.5))
    pairs.append(('text on gap note', ratio(rgba(c['text']), rgba(c['gap-bg'])), 4.5))
    for s in surf[:3]:
        pairs.append(('control', ratio(rgba(c['control']), s), 3.0))
    for name, r, floor in pairs:
        if r < floor - 1e-9:
            fail(f'contrast ({theme}): {name} is {r:.2f}:1, below {floor}:1')
    LOWEST[theme] = min(r for _, r, f in pairs if f == 4.5)

